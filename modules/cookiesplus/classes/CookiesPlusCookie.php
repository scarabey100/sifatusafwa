    public function __construct($id = null, $id_lang = null, $id_shop = null, $translator = null)
    {
        global $_FIELDS;

        $module = Module::getInstanceByName($this->module_name);

        $_FIELDS[get_class($this) . '_' . md5('id_cookiesplus_finality')] = $module->l('Cookie finality');
        $_FIELDS[get_class($this) . '_' . md5('name')] = $module->l('Cookie name');

        parent::__construct($id, $id_lang, $id_shop, $translator);
    }

    public function add($autodate = true, $null_values = false)
    {
        $this->id_shop = ($this->id_shop) ?: Context::getContext()->shop->id;

        return parent::add($autodate, $null_values);
    }

    public function update($null_values = false)
    {
        $result = parent::update($null_values);

        if (Tools::getValue('back') && (int) Tools::getvalue('id_cookiesplus_finality')) {
            Tools::redirectAdmin(Context::getContext()->link->getAdminLink('AdminCookiesPlusFinalities') . '&updatecookiesplus_finality=&conf=4&id_cookiesplus_finality=' . (int) Tools::getvalue('id_cookiesplus_finality'));
        }

        return $result;
    }

    public static function getCookiesPlusCookies($id_cookiesplus_finality, $id_lang = null, $only_active = false, $id_shop = null, $light = false)
    {
        if ($id_shop === null) {
            $id_shop = (int) Context::getContext()->shop->id;
        }

        if ($light) {
            $select = 'cc.name';
        } else {
            $select = '*';
        }
        $query = '
            SELECT ' . $select . '
            FROM ' . _DB_PREFIX_ . 'cookiesplus_cookie cc '
            . 'LEFT JOIN ' . _DB_PREFIX_ . 'cookiesplus_cookie_lang ccl on cc.`id_cookiesplus_cookie` = ccl.`id_cookiesplus_cookie`
            WHERE
                `id_cookiesplus_finality` = ' . (int) $id_cookiesplus_finality . '
                AND ccl.`id_lang` = ' . ($id_lang ? (int) $id_lang : (int) Context::getContext()->language->id) .
                ($only_active ? ' AND cc.`active` = 1' : '') .
                ' AND cc.`id_shop` =  ' . $id_shop .
            ' ORDER BY cc.`name`;
        ';

        return Db::getInstance()->executeS($query);
    }

